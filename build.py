#!/usr/bin/env python3
"""build.py — assemble Subhasta into one file.

    python3 build.py            writes build/rostrum.html (the artifact page) and build/preview.html (a local wrapper)
    python3 build.py --share    also writes build/share.html: the same page with the owner's own lines on the Desk (the default
                                two lines about him and his signature) replaced by neutral ones, for the shareable copy

The page is src/page.html with every placeholder comment replaced by the text of a source file, in this order:
  /*__CSS__*/            src/style.css
  /*__DATA_HOUSES__*/    src/data_houses.js        (plain global const declarations; order matters)
  /*__DATA_MARKET__*/    src/data_market.js
  /*__DATA_MORE__*/      src/data_more.js
  /*__DATA_PEOPLE__*/    src/data_people.js
  /*__DATA_REEL__*/      src/data_reel.js          (its /*__IMGMETA__*/{} becomes data/images_meta.json)
  /*__DATA_UNDER__*/     src/data_under.js
  /*__DATA_PULSE__*/     src/data_pulse.js
  /*__DATA_ATLAS__*/     src/data_atlas.js
  /*__DATA_WORLD__*/     src/data_world.js
  /*__DATA_FLOWS__*/     src/data_flows.js         (trade in art, attention, rates)
  /*__DATA_GLOBE__*/     src/data_globe.js         (generated dot mask for the globe)
  /*__DATA_CIRCLE__*/    src/data_circle.js        (the Circle: offer, value points, brief)
  /*__DATA_BENCH__*/     src/data_bench.js         (generated by tools/benchmarks.py: S&P 500, gold, CPI)
  /*__DATA_MOVEMENTS__*/ src/data_movements.js     (v22: art movements as the market reads them)
  /*__DATA_LIVE__*/      src/data_live.js          (v22: the live layer's baked copy — the Read, the sale room, the desk's status — and KB)
  /*__DATA_NAV__*/       src/data_nav.js           (v24: the Navigator's rules, generated by tools/gen_research.py from data/research/bundle.json)
  /*__DATA_SEASON__*/    src/data_season.js        (v24: the Season and the Horizon, generated by tools/gen_research.py from data/research/bundle.json)
  /*__DATA_NET__*/       src/data_net.js           (v25: the Net, the money behind the sales, the Transformation; generated the same way)
  /*__DATA_EYE__*/       src/data_eye.js           (v29: the Eye's places: the Library's pictures located, the gazetteer of places and cultures)
  /*__DATA_SCHOOL__*/    src/data_school.js        (v29: the Eye's pool of open-collection works and the School, generated by tools/gen_research.py)
  /*__DATA_LANDMARKS__*/ src/data_landmarks.js     (v32: one engraved landmark per city, generated by tools/gen_landmarks.py from data/landmarks.json)
  /*__DATA_REGIONS__*/   src/data_regions.js       (v33: regions, rivers, lakes, places from Natural Earth, generated by tools/gen_regions.py)
  /*__DATA_HISTORY__*/   src/data_history.js       (v33: the Then mode's historical layer, generated by tools/gen_history.py)
  /*__DATA_OBJECTS__*/   src/data_objects.js       (v34: the objects of value and the lots' pictures, generated by tools/gen_objects.py)
  /*__NGA__*/[]          data/nga_subset.json       (the Ledger's 771 provenance records)
  /*__APP__*/            src/app.js, with /*__UNDER__*/ /*__PULSE__*/ /*__ATLAS__*/ /*__CLINIC__*/ /*__GLOBE__*/ /*__CIRCLE__*/
                         /*__LAB__*/ /*__LABPROV__*/ /*__LABHANDS__*/ /*__TODAY__*/ /*__MOVE__*/ /*__ASK__*/ /*__WORLD__*/ /*__LIBRARY__*/ /*__COMPARE__*/ /*__NAV__*/ /*__SEASON__*/ replaced by src/under.js,
                         src/pulse.js, src/atlas.js, src/clinic.js, src/globe.js, src/circle.js, src/lab.js, src/lab_prov.js,
                         src/lab_hands.js, src/today.js, src/move.js, src/ask.js, src/world.js, src/library.js, src/compare.js, src/nav.js, src/season.js (the Season and the Horizon);
                         style.css is followed by globe.css, circle.css, lab.css, ask.css, world.css, library.css and nav.css (the Navigator, the Season and the Horizon)
  /*__REEL__*/           src/reel.js
and the count tokens ${ALLCOUNT} ${PEOPLECOUNT} ${LOTCOUNT} ${NGACOUNT} ${UNDERCOUNT} ${HUBCOUNT} ${SEGCOUNT} ${INSTCOUNT} ${MOVECOUNT}
(colophon and the Reel's closing card) replaced by the sizes of the collections. The counts come from evaluating
the data files in Node (the same way tools/lint_data.js does); if Node is unavailable the build falls back to a
regex count over the source text and says so.

The build refuses to write when a placeholder is missing or doubled, when any pasted text contains "</script"
(it would end the page's script element), or when a count is zero.
"""
import json, re, pathlib, subprocess, sys

root = pathlib.Path(__file__).resolve().parent
src = root / 'src'
read = lambda p: p.read_text(encoding='utf-8')

DATA_ORDER = ['data_houses', 'data_market', 'data_more', 'data_people', 'data_reel', 'data_under', 'data_pulse', 'data_atlas', 'data_world', 'data_flows', 'data_globe', 'data_circle', 'data_bench', 'data_movements', 'data_live', 'data_places', 'data_nav', 'data_season', 'data_net', 'data_eye', 'data_school', 'data_landmarks', 'data_regions', 'data_history', 'data_objects']
page = read(src / 'page.html')
css = read(src / 'style.css') + '\n' + read(src / 'globe.css') + '\n' + read(src / 'circle.css') + '\n' + read(src / 'lab.css') + '\n' + read(src / 'ask.css') + '\n' + read(src / 'world.css') + '\n' + read(src / 'library.css') + '\n' + read(src / 'nav.css') + '\n' + read(src / 'polish.css')
data = {n: read(src / f'{n}.js') for n in DATA_ORDER}
imeta = json.load(open(root / 'data' / 'images_meta.json', encoding='utf-8'))
imeta_js = json.dumps(imeta, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/')
assert data['data_reel'].count('/*__IMGMETA__*/{}') == 1, 'data_reel.js must carry exactly one /*__IMGMETA__*/{} placeholder'
data['data_reel'] = data['data_reel'].replace('/*__IMGMETA__*/{}', imeta_js)
nga = json.load(open(root / 'data' / 'nga_subset.json', encoding='utf-8'))
nga_js = json.dumps(nga, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/')
app = read(src / 'app.js')
for ph, f in (('/*__UNDER__*/', 'under.js'), ('/*__PULSE__*/', 'pulse.js'), ('/*__ATLAS__*/', 'atlas.js'), ('/*__CLINIC__*/', 'clinic.js'), ('/*__GLOBE__*/', 'globe.js'), ('/*__CIRCLE__*/', 'circle.js'), ('/*__LAB__*/', 'lab.js'), ('/*__LABPROV__*/', 'lab_prov.js'), ('/*__LABHANDS__*/', 'lab_hands.js'), ('/*__TODAY__*/', 'today.js'), ('/*__MOVE__*/', 'move.js'), ('/*__ASK__*/', 'ask.js'), ('/*__WORLD__*/', 'world.js'), ('/*__LIBRARY__*/', 'library.js'), ('/*__COMPARE__*/', 'compare.js'), ('/*__NAV__*/', 'nav.js'), ('/*__SEASON__*/', 'season.js'), ('/*__DEAL__*/', 'deal.js'), ('/*__OCEAN__*/', 'ocean.js'), ('/*__BRIEF__*/', 'brief.js'), ('/*__EYE__*/', 'eye.js'), ('/*__SCHOOL__*/', 'school.js')):
    assert app.count(ph) == 1, f'app.js must carry exactly one {ph}'
    app = app.replace(ph, read(src / f))
reel = read(src / 'reel.js')

# ---- counts: evaluate the data in Node; fall back to regexes over the source text ----
COUNT_JS = r"""
const fs=require('fs'),vm=require('vm');const [srcDir,imetaPath]=process.argv.slice(1); // node -e: argv[0] is node, then our two arguments
const ctx=vm.createContext({});
for(const f of %s){let t=fs.readFileSync(srcDir+'/'+f+'.js','utf8');if(f==='data_reel')t=t.replace('/*__IMGMETA__*/{}',fs.readFileSync(imetaPath,'utf8'));vm.runInContext(t.replace(/^const /mg,'var '),ctx);}
const n=o=>Array.isArray(o)?o.length:0;
console.log(JSON.stringify({ALLCOUNT:n(ctx.HOUSES)+n(ctx.PLAYERS),PEOPLECOUNT:n(ctx.PEOPLE),LOTCOUNT:n(ctx.RESULTS)+n(ctx.RESULTS_MORE),UNDERCOUNT:n(ctx.ATLAS),HUBCOUNT:n(ctx.HUBS),SEGCOUNT:n(ctx.SEGMENTS),INSTCOUNT:n(ctx.INSTITUTIONS),MOVECOUNT:n(ctx.MOVEMENTS)}));
""" % json.dumps(DATA_ORDER)

def counts_from_node():
    r = subprocess.run(['node', '-e', COUNT_JS, str(src), str(root / 'data' / 'images_meta.json')], capture_output=True, text=True, timeout=60)
    if r.returncode != 0:
        raise RuntimeError(r.stderr.strip()[:400])
    return json.loads(r.stdout.strip().splitlines()[-1])

def counts_from_regex():
    def block(text, start, end):
        a = text.split(start)
        if len(a) < 2: raise SystemExit(f'regex count: "{start}" not found')
        return a[1].split(end)[0]
    d = data
    return {
        'ALLCOUNT': len(re.findall(r"\n\{id:'", d['data_houses'])),
        'PEOPLECOUNT': len(re.findall(r"\n\{n:'", d['data_people'])),
        'LOTCOUNT': len(re.findall(r"\n\{artist:'", d['data_market'])) + len(re.findall(r"\n\{artist:'", d['data_more'])),
        'UNDERCOUNT': len(re.findall(r"\n\{id:'", block(d['data_under'], 'const ATLAS=', 'const CHECKS'))),
        'HUBCOUNT': len(re.findall(r"\n\{id:'", block(d['data_atlas'], 'const HUBS=', 'const COUNTRY_SHARE'))),
        'SEGCOUNT': len(re.findall(r"\n\{id:'", block(d['data_atlas'], 'const SEGMENTS=', 'const FAIRS'))),
        'INSTCOUNT': len(re.findall(r"\n\{id:'", block(d['data_atlas'], 'const INSTITUTIONS=', 'const INST_FACTS'))),
        'MOVECOUNT': len(re.findall(r"\n\{id:'", d['data_movements'])),
    }

try:
    counts = counts_from_node(); how = 'node'
except Exception as ex:  # Node missing or the data failed to evaluate
    print(f'warning: counting with regexes ({ex})', file=sys.stderr)
    counts = counts_from_regex(); how = 'regex'
counts['NGACOUNT'] = len(nga)
for k, v in counts.items():
    if not v:
        raise SystemExit(f'count {k} is 0: a collection is empty or not where the build expects it')

# ---- guards ----
pieces = {'style.css': css, 'app.js (with engines)': app, 'reel.js': reel, **{f'{n}.js': t for n, t in data.items()}, 'nga_subset.json': nga_js, 'images_meta.json': imeta_js}
for name, text in pieces.items():
    if '</script' in text.lower():
        raise SystemExit(f'{name} contains "</script": it would end the page\'s script element')
PLACEHOLDERS = ['/*__CSS__*/'] + [f'/*__{n.upper()}__*/' for n in DATA_ORDER] + ['/*__NGA__*/[]', '/*__APP__*/', '/*__REEL__*/']
for ph in PLACEHOLDERS:
    if page.count(ph) != 1:
        raise SystemExit(f'placeholder {ph} occurs {page.count(ph)} times in page.html (must be exactly once)')

# ---- assemble ----
out = page.replace('/*__CSS__*/', css)
for n in DATA_ORDER:
    out = out.replace(f'/*__{n.upper()}__*/', data[n])
out = out.replace('/*__NGA__*/[]', nga_js).replace('/*__APP__*/', app).replace('/*__REEL__*/', reel)
for k, v in counts.items():
    out = out.replace('${' + k + '}', str(v))
left = re.findall(r'/\*__[A-Z_]+__\*/|\$\{[A-Z]+COUNT\}', out)
if left:
    raise SystemExit(f'unreplaced placeholders remain in the output: {sorted(set(left))}')

(root / 'build').mkdir(exist_ok=True)
# the Eye's atlas sheets (v29): inside an artifact the sheets are assets (the 511-file cap), served at /_blob/<id>; data/eye_assets.json
# maps each sheet to its asset URL per artifact ({"main": {"img/eye/a000.jpg": "/_blob/…", …}, "share": {…}}); the artifact copies get
# the mapped URLs, the website and the preview keep the relative paths. A sheet without a mapping keeps its path (and will not show there).
ASSETS = json.loads((root / 'data' / 'eye_assets.json').read_text(encoding='utf-8')) if (root / 'data' / 'eye_assets.json').exists() else {}
def with_assets(text, key):
    m = ASSETS.get(key) or {}
    if not m:
        return text
    def sub(mt):
        files = json.loads(mt.group(1))
        return 'const EYE_SHEETS=' + json.dumps([m.get(f, f) for f in files], separators=(',', ':')) + ';'
    text2, n = re.subn(r'const EYE_SHEETS=(\[[^\]]*\]);', sub, text, count=1)
    if n != 1:
        raise SystemExit('EYE_SHEETS not found for the asset mapping')
    # v33: the border snapshots of the Then mode are assets in the artifacts too (data/hist_assets.json: {key: {"1500": "/_blob/<id>", …}})
    hm = HIST_ASSETS.get(key) or {}
    if hm:
        text2, n2 = re.subn(r'const HIST_ASSETS=\{\};', 'const HIST_ASSETS=' + json.dumps(hm, separators=(',', ':')) + ';', text2, count=1)
        if n2 != 1:
            raise SystemExit('HIST_ASSETS not found for the asset mapping')
    # v34: the pictures of HIST_PICS (docs/img/v34/<key>.jpg on the website) are assets in the artifacts (data/pic_assets.json: {key: {"img/v34/x.jpg": "/_blob/<id>"}});
    # a picture without a mapping keeps its path and does not show there
    pm = PIC_ASSETS.get(key) or {}
    if pm:
        text2 = re.sub(r'"src":"(img/v34/[^"]+)"', lambda mt: '"src":"' + pm.get(mt.group(1), mt.group(1)) + '"', text2)
    return text2
HIST_ASSETS = json.loads((root / 'data' / 'hist_assets.json').read_text(encoding='utf-8')) if (root / 'data' / 'hist_assets.json').exists() else {}
PIC_ASSETS = json.loads((root / 'data' / 'pic_assets.json').read_text(encoding='utf-8')) if (root / 'data' / 'pic_assets.json').exists() else {}
(root / 'build' / 'rostrum.html').write_text(with_assets(out, 'main'), encoding='utf-8')
# the website (v29): docs/index.html beside docs/img — a complete document for GitHub Pages or any static host; the artifact's
# skeleton is written here by hand (the Artifact tool adds its own); the page's <title> and <style> sit in the body as the tool expects
(root / 'docs').mkdir(exist_ok=True)
(root / 'docs' / 'index.html').write_text('<!doctype html><html lang="en-GB"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><meta name="description" content="Subhasta: the art trade’s terminal — the Eye, the School, the Hammer, the Navigator, the Walls, the Tides. Every figure sourced."><style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}body{margin:0;font:14px system-ui}img{max-width:100%}[hidden]{display:none!important}</style></head><body>' + out + '</body></html>', encoding='utf-8')
(root / 'build' / 'preview.html').write_text('<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}body{margin:0;font:14px system-ui}img{max-width:100%}[hidden]{display:none!important}</style></head><body>' + out + '</body></html>', encoding='utf-8')
# ---- the shareable copy: the Desk's lines about the owner become neutral ----
if '--share' in sys.argv[1:]:
    SHARE = [("const DEFAULT_BIO='Senior at George Washington University (International Business, finance concentration), president of the Russian Student Association, building open-data tools for the art market; aiming at private sales and collection management for ultra-high-net-worth clients.';",
              "const DEFAULT_BIO='Two lines about you: who you are, what you are building, and why this person.';"),
             ("With thanks and best regards,\\nMikhail Tikhomirov\\nGeorge Washington University, Washington, DC", "With thanks and best regards,\\n[Your name]")]
    shared = out
    for a, b in SHARE:
        if shared.count(a) != 1:
            raise SystemExit(f'--share: expected one {a[:60]!r}, found {shared.count(a)}')
        shared = shared.replace(a, b)
    (root / 'build' / 'share.html').write_text(with_assets(shared, 'share'), encoding='utf-8')
    print('built build/share.html (neutral Desk lines)')
print(f"built {len(out)//1024} KB; orgs {counts['ALLCOUNT']} lots {counts['LOTCOUNT']} people {counts['PEOPLECOUNT']} ledger {counts['NGACOUNT']} undercurrents {counts['UNDERCOUNT']} hubs {counts['HUBCOUNT']} segments {counts['SEGCOUNT']} institutions {counts['INSTCOUNT']} movements {counts['MOVECOUNT']} (counted by {how})")
