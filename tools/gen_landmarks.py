#!/usr/bin/env python3
"""Write src/data_landmarks.js from data/landmarks.json (v32): LANDMARKS = {city: {n, w, p: [[x,y,x,y,…], …]}} in a 100×100 box,
y down, the ground at y=100. The World draws one at each city when the globe is close (world.js drawLandmarks). The drawings are the
desk's own line art of each building's silhouette (no traced image). A path with fewer than two points, or a point outside the box, is dropped."""
import json, pathlib, sys
root = pathlib.Path(__file__).resolve().parent.parent
src = json.load(open(root / 'data' / 'landmarks.json', encoding='utf-8'))
out, bad = {}, []
for it in src.get('items', []):
    city = it.get('city'); paths = []
    for p in it.get('paths', []):
        flat = []
        for pt in p:
            if not (isinstance(pt, (list, tuple)) and len(pt) == 2): continue
            x, y = float(pt[0]), float(pt[1])
            if x < -2 or x > 102 or y < -2 or y > 102: bad.append((city, x, y)); continue
            flat += [round(x, 1), round(y, 1)]
        if len(flat) >= 4: paths.append(flat)
    if city and paths: out[city] = {'n': it.get('n') or it.get('name') or '', 'w': float(it.get('w') or 1), 'p': paths}
head = ("/* data_landmarks.js — generated by tools/gen_landmarks.py from data/landmarks.json (v32, %s). LANDMARKS: {city: {n, w, p}}: one engraved\n"
        "   landmark per city as polylines in a 100×100 box (y down, the ground at y=100), drawn at the city when the World is close (world.js). */\n") % src.get('asof', '')
(root / 'src' / 'data_landmarks.js').write_text(head + 'const LANDMARKS=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
print(f"wrote src/data_landmarks.js: {len(out)} landmarks ({', '.join(out)}); {len(bad)} points outside the box dropped")
