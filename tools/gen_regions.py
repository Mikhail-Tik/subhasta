#!/usr/bin/env python3
"""Write src/data_regions.js from Natural Earth (public domain; naturalearthdata.com): the first-level regions of every country
(10m admin-1 boundary lines), the principal rivers (50m), the large lakes (50m) and the populated places (50m), each simplified for the
globe at zoom. Usage: python3 tools/gen_regions.py <natural-earth geojson dir>. The output holds polylines as flat [lon,lat,…] arrays,
quantised to 0.01°, Douglas–Peucker simplified (regions 0.03°, rivers 0.04°, lakes 0.05°)."""
import json, math, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = pathlib.Path(sys.argv[1])

def dp(pts, tol):
    if len(pts) < 3: return pts
    # iterative Douglas–Peucker
    keep = [False] * len(pts); keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = pts[a]; bx, by = pts[b]
        dx, dy = bx - ax, by - ay; L2 = dx * dx + dy * dy
        best, bi = -1.0, -1
        for i in range(a + 1, b):
            px, py = pts[i]
            if L2 == 0: d = math.hypot(px - ax, py - ay)
            else:
                t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / L2))
                d = math.hypot(px - (ax + t * dx), py - (ay + t * dy))
            if d > best: best, bi = d, i
        if best > tol and bi > 0:
            keep[bi] = True; stack.append((a, bi)); stack.append((bi, b))
    return [p for p, k in zip(pts, keep) if k]

def rank(p, k='scalerank'):
    v = p.get(k)
    return 9 if v is None else int(v)

def lines_of(geom):
    if not geom: return []
    t = geom['type']; c = geom['coordinates']
    if t == 'LineString': return [c]
    if t == 'MultiLineString': return list(c)
    if t == 'Polygon': return list(c)
    if t == 'MultiPolygon': return [r for poly in c for r in poly]
    return []

def flat(pts):
    # integers in hundredths of a degree, delta-encoded after the first point: [x0, y0, dx1, dy1, …]
    out, px, py = [], 0, 0
    for i, (x, y) in enumerate(pts):
        X, Y = int(round(x * 100)), int(round(y * 100))
        if i == 0: out += [X, Y]
        else:
            if X == px and Y == py: continue
            out += [X - px, Y - py]
        px, py = X, Y
    return out

def build(path, tol, minpts=2, keep=lambda f: True, cosine=True):
    d = json.load(open(src / path, encoding='utf-8'))
    out, n = [], 0
    for f in d['features']:
        if not keep(f): continue
        for ln in lines_of(f['geometry']):
            pts = [(float(x), float(y)) for x, y in ln]
            # scale the tolerance by latitude so the simplification is even on the sphere
            s = dp(pts, tol)
            if len(s) >= minpts: out.append(flat(s)); n += len(s)
    return out, n

regions, nr = build('ne_10m_admin_1_states_provinces_lines.geojson', 0.04, minpts=2, keep=lambda f: (f['properties'].get('MIN_ZOOM') or 0) <= 7)
rivers_d = json.load(open(src / 'ne_50m_rivers_lake_centerlines.geojson', encoding='utf-8'))
rivers = []
for f in rivers_d['features']:
    p = f['properties']
    if rank(p) > 6: continue
    for ln in lines_of(f['geometry']):
        s = dp([(float(x), float(y)) for x, y in ln], 0.04)
        if len(s) >= 2: rivers.append({'n': p.get('name_en') or p.get('name') or '', 'r': rank(p), 'p': flat(s)})
lakes, nl = build('ne_50m_lakes.geojson', 0.05, minpts=4, keep=lambda f: rank(f['properties']) <= 3)
places_d = json.load(open(src / 'ne_50m_populated_places_simple.geojson', encoding='utf-8'))
places = []
for f in places_d['features']:
    p = f['properties']; x, y = f['geometry']['coordinates']
    places.append([p.get('name') or p.get('nameascii') or '', round(float(x), 2), round(float(y), 2), rank(p), 1 if p.get('adm0cap') else 0])
places.sort(key=lambda r: (r[3], r[0]))
head = ("/* data_regions.js — generated by tools/gen_regions.py from Natural Earth (public domain). NE_REGIONS: first-level boundary lines of every\n"
        "   country (10m admin-1 at MIN_ZOOM ≤ 7, simplified 0.04°); NE_RIVERS: principal rivers (50m, scalerank ≤ 6); NE_LAKES: the largest lakes (50m, scalerank ≤ 3);\n"
        "   NE_PLACES: populated places (50m): [name, lon, lat, scalerank, capital]. Lines are integers in hundredths of a degree,\n"
        "   delta-encoded after the first point ([x0, y0, dx1, dy1, …]); glbDecode() in globe.js turns them into unit vectors. Drawn when close. */\n")
js = head + 'const NE_REGIONS=' + json.dumps(regions, separators=(',', ':')) + ';\n' + 'const NE_RIVERS=' + json.dumps(rivers, ensure_ascii=False, separators=(',', ':')) + ';\n' + \
     'const NE_LAKES=' + json.dumps(lakes, separators=(',', ':')) + ';\n' + 'const NE_PLACES=' + json.dumps(places, ensure_ascii=False, separators=(',', ':')) + ';\n'
(root / 'src' / 'data_regions.js').write_text(js, encoding='utf-8')
print(f"wrote src/data_regions.js: {len(regions)} region lines ({nr} pts), {len(rivers)} rivers, {len(lakes)} lakes ({nl} pts), {len(places)} places; {len(js)//1024} KB")
